/*

    This script is responsible for building our webview's HTML and JS into a
    single generated minified output file (src/components/generated/force-graph-html.js)
    that can be imported by our react component and used for the WebView source

*/

import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import { colors } from "../src/theme/colors.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

// esbuild will scan our entry file and resolve the npm imports, then bundle/minify
// the resulting js
const result = await build({
    entryPoints: [resolve(root, 'web/force-graph-entry.js')],
    bundle: true,
    minify: true,
    format: 'iife',
    platform: 'browser',
    write: false,
});

const js = result.outputFiles[0].text;

const bgcolor = colors.background;

const html = `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,user-scalable=no">
<style>
  * { margin: 0; padding: 0; box-sizing: border-box; }
  html, body { width: 100%; height: 100%; overflow: hidden; background: ${bgcolor}; }
  #graph { width: 100%; height: 100%; }
  [class*="nav-info"] { display: none !important; }
</style>
</head>
<body>
<div id="graph"></div>
<script>${js}</script>
</body>
</html>`;

const outDir = resolve(root, 'src/components/generated');
mkdirSync(outDir, { recursive: true });

writeFileSync(
    resolve(outDir, 'force-graph-html.js'),
    `// Auto-generated by scripts/bundle-force-graph.mjs — do not edit.\nexport default ${JSON.stringify(html)};\n`
);

console.log('Bundled force-graph HTML to src/components/generated/force-graph-html.js');
